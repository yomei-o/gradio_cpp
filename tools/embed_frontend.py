#!/usr/bin/env python3
"""Embed frontend/index.html into include/gradio_frontend.hpp.

MSVC limits a single string literal to ~16 KB, so the page is split into
chunks kept in an array and joined once at runtime.

    python tools/embed_frontend.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "frontend" / "index.html"
DST = ROOT / "include" / "gradio_frontend.hpp"
CHUNK = 12000
DELIM = "GRFE"

text = SRC.read_text(encoding="utf-8")
assert f'){DELIM}"' not in text
data = text.encode("utf-8")

chunks = []
i = 0
while i < len(data):
    j = min(i + CHUNK, len(data))
    while j < len(data) and (data[j] & 0xC0) == 0x80:  # don't split a UTF-8 sequence
        j -= 1
    chunks.append(data[i:j].decode("utf-8"))
    i = j

out = [
    "// Generated by tools/embed_frontend.py from frontend/index.html. Do not edit.",
    "#pragma once",
    "#include <string>",
    "",
    "namespace gr {",
    "inline const std::string& frontend_html() {",
    "    static const char* const parts[] = {",
]
for c in chunks:
    out.append(f'        R"{DELIM}({c}){DELIM}",')
out += [
    "    };",
    "    static const std::string html = [] {",
    "        std::string s;",
    "        for (const char* p : parts) s += p;",
    "        return s;",
    "    }();",
    "    return html;",
    "}",
    "}  // namespace gr",
    "",
]
DST.write_text("\n".join(out), encoding="utf-8", newline="\n")
print(f"{DST.relative_to(ROOT)}: {len(data)} bytes in {len(chunks)} chunk(s)")
